N_ITEMS = 12          # the rig's null config (spec 2.4)
P_EDGE = 0.45         # ~29-32 edges: the deployment-realistic regime of PP4
BETA, GAMMA = 0.25, 2.0
ALPHA = 0.05
N_GRAPHS = 4          # masks held FIXED across replicates: the pre-specified case
# 64 is here for a specific question, not for grid symmetry: comparison-level
# thinning splits an edge's k comparisons into two folds of k/2, so a deployment
# running k=128 and thinning is doing inference on folds of 64. Measuring 64
# against 128 prices what thinning costs in separation (RAN-29).
K_GRID = (8, 32, 64, 128, 512)


def seed(*parts) -> np.random.Generator:
    """Deterministic per-cell stream. No wall-clock, per spec 9."""
    h = hashlib.sha256("|".join(map(str, parts)).encode()).digest()
    return np.random.default_rng(int.from_bytes(h[:8], "big"))


def graph(g: int):
    """Mask g, fixed. Redrawing this inside a replicate loop would test the
    random-graph case, which is NOT the case the collapse claim is about."""
    return flows.sample_sparse_graph(N_ITEMS, P_EDGE, seed("graph", g))


def eta_in_S(D0, D1, rho_curl, g):
    """A natural parameter satisfying H0 exactly: gradient + rho_curl * curl.

    Both components lie in S, so ||P_h eta|| = 0 by construction and any
    rejection is a false one. The curl term is what separates this null from
    Bradley-Terry; at rho_curl = 0 the two are being fed the same data.
    """
    eta = D0 @ flows.theta_gamma(N_ITEMS, BETA, GAMMA)
    if rho_curl and D1.shape[0]:
        c = seed("curl", g).normal(size=D1.shape[0])
        curl = D1.T @ c
        eta = eta + rho_curl * np.linalg.norm(eta) / np.linalg.norm(curl) * curl
    return eta


def run_cell(eta, k, bases, tag, reps):
    """Draw `reps` replicates at fixed eta; return the USABLE statistics and the loss.

    Separated draws (some edge at w=0 or w=k, so the constrained MLE diverges)
    are dropped and counted. They are not a small-print detail at k=8: that is
    where the drop rate is largest and where any claim about the null's shape is
    least trustworthy, so the rate travels with every number computed from T.

    `off` is the max score_off_harmonic over the SURVIVING draws, and is None
    when none survived -- 0.0 there would read as perfect orthogonality on the
    one cell that measured nothing.
    """
    p = st.sigmoid(eta)          # exact link, never the fitter's clip: the row
                                 # must describe the eta it was actually handed
    T, off, dropped = [], None, 0
    for r in range(reps):
        w = flows.btl_counts(p, k, seed(tag, r))
        s = st.score_statistic(w, k, bases)
        if not s["usable"]:
            dropped += 1
            continue
        T.append(s["T"])
        off = s["score_off_harmonic"] if off is None else max(off, s["score_off_harmonic"])
    return np.array(T), off, dropped


# ---------------------------------------------------------------- probe 1
def chi2_collapse(reps=2000):
    rows = []
    for filling in ("observed", "empty"):
        for g in range(N_GRAPHS):
            edges = graph(g)
            D0, D1 = st.operators(N_ITEMS, edges, filling)
            bases = st.harmonic_zero_bases(D0, D1)
            df = bases[0].shape[1]
            eta = eta_in_S(D0, D1, 1.0, g)
            for k in K_GRID:
                T, off, dropped = run_cell(eta, k, bases, f"c1|{filling}|{g}|{k}", reps)
                ks = kstest(T, "chi2", args=(df,)) if len(T) > 20 else None
                rows.append({
                    "filling": filling, "graph": g, "E": len(edges), "df": df, "k": k,
                    # Carried so the cross-filling comparison is not read naively:
                    # eta_in_S adds curl scaled to ||eta||, but on 'empty' there
                    # are no 2-cells so the curl term is a no-op. The 'observed'
                    # cells therefore carry a LARGER ||eta||, which is why their
                    # separation rate at k=8 is not comparable to 'empty'. The
                    # chi2(b1) claim is per-cell, so this does not touch it.
                    "eta_absmax": float(np.max(np.abs(eta))),
                    "p_min": float(min(st.sigmoid(eta).min(),
                                       1 - st.sigmoid(eta).max())),
                    "n_usable": int(len(T)), "n_dropped": dropped,
                    "drop_rate": float(dropped / reps),
                    "mean_T": float(T.mean()) if len(T) else None, "chi2_mean": df,
                    "var_T": float(T.var(ddof=1)) if len(T) > 1 else None,
                    "chi2_var": 2 * df,
                    "reject_rate": (float((T > chi2.ppf(1 - ALPHA, df)).mean())
                                    if len(T) else None),
                    "ks_stat": float(ks.statistic) if ks else None,
                    "ks_p": float(ks.pvalue) if ks else None,
                    "score_off_harmonic_max": off,
                })
    # The collapse is ASYMPTOTIC in k, so the verdict is about the large-k end
    # and about the trend, not about whether every cell passes at k=8.
    at_max_k = [r for r in rows if r["k"] == max(K_GRID)]
    # `<= 0.05`, not `< 0.05`: the strict form silently dropped a cell sitting at
    # exactly 5% loss -- the heaviest-separation cell, and so the one most able to
    # break the claim -- from the gate that everything downstream rests on. The
    # count of what IS excluded now ships alongside the verdict, as it already
    # does for the other two probes.
    big = [r for r in at_max_k if r["ks_p"] is not None and r["drop_rate"] <= 0.05]
    obs_big = [r for r in big if r["filling"] == "observed"]
    frac_ok = sum(r["ks_p"] > 0.01 for r in big) / len(big) if big else 0.0
    # No judged cell is NOT evidence against the claim: say so rather than
    # reporting the gate as refuted on an empty sample (cf. the sibling probes).
    verdict = ("inconclusive" if not big
               else "confirmed" if obs_big and all(r["ks_p"] > 0.01 for r in obs_big)
               else "partial" if frac_ok >= 0.5 else "refuted")
    return {
        "probe": "chi2_collapse",
        "question": "On a pre-specified fixed graph, is the harmonic-zero score "
                    "statistic distributed chi2(b1)?",
        "falsifies": "If the KS test against chi2(b1) rejects at the largest k, "
                     "the collapse to a classical Rao test is wrong and the "
                     "referee-proof claim goes with it.",
        "verdict": verdict,
        "value": {"alpha": ALPHA, "reps": reps,
                  "n_cells_at_max_k": len(at_max_k), "n_cells_judged": len(big),
                  "n_cells_excluded_for_separation": len(at_max_k) - len(big),
                  "rows": rows},
    }


# ---------------------------------------------------------------- probe 2
def curl_freedom(reps=1500, k=128):
    """Feed both nulls the SAME data and vary how much curl H0-true eta carries.

    Harmonic-zero should hold its size; Bradley-Terry should inflate, because
    curl is outside im D0. Only meaningful on 'observed': with filling='empty'
    there are no 2-cells, im D1^T = {0}, and the two nulls are literally the
    same test.
    """
    rows = []
    for g in range(N_GRAPHS):
        edges = graph(g)
        D0, D1 = st.operators(N_ITEMS, edges, "observed")
        hz, bt = st.harmonic_zero_bases(D0, D1), st.bradley_terry_bases(D0)
        grad = eta_in_S(D0, D1, 0.0, g)      # loop-invariant: the pure-gradient part
        for rho in (0.0, 0.5, 1.0, 2.0, 4.0):
            eta = eta_in_S(D0, D1, rho, g)
            row = {"graph": g, "rho_curl": rho,
                   # Carried so an extreme cell is visible as extreme: the link is
                   # exact, so a large |eta| means near-deterministic edges and a
                   # high separation rate, not a silently truncated flow.
                   "eta_absmax": float(np.max(np.abs(eta))),
                   "curl_frac": float(np.linalg.norm(eta - grad)
                                      / np.linalg.norm(eta))}
            # The tag deliberately omits `name`: both nulls must see the SAME
            # draws, or the comparison is unpaired and no per-draw claim holds.
            for name, bases in (("harmonic_zero", hz), ("bradley_terry", bt)):
                T, _, dropped = run_cell(eta, k, bases, f"c2|{g}|{rho}", reps)
                df = bases[0].shape[1]
                row[f"{name}_df"] = df
                row[f"{name}_n_usable"] = int(len(T))
                row[f"{name}_drop_rate"] = float(dropped / reps)
                row[f"{name}_reject"] = (float((T > chi2.ppf(1 - ALPHA, df)).mean())
                                         if len(T) > 20 else None)
            rows.append(row)
    # Judge only where curl is present AND the sample survived. At rho_curl=4
    # the flow is ~97% curl, eta is extreme, and separation removes most or all
    # draws -- a degenerate regime, not evidence either way. Excluded cells are
    # COUNTED here rather than quietly dropped from the range.
    with_curl = [r for r in rows if r["rho_curl"] > 0]
    usable = [r for r in with_curl
              if r["harmonic_zero_drop_rate"] < 0.05
              and r["bradley_terry_drop_rate"] < 0.05
              and r["harmonic_zero_reject"] is not None
              and r["bradley_terry_reject"] is not None]
    hz_max = max((r["harmonic_zero_reject"] for r in usable), default=None)
    # BT's MINIMUM is the binding number: the claim is that BT inflates wherever
    # curl is present, so the weakest inflation is what has to clear the bar.
    bt_min = min((r["bradley_terry_reject"] for r in usable), default=None)
    verdict = ("confirmed" if usable and hz_max < 0.10 and bt_min > 0.30
               else "refuted" if usable else "inconclusive")
    return {
        "probe": "curl_freedom",
        "question": "Does the harmonic-zero null absorb curl where Bradley-Terry "
                    "rejects on it?",
        "falsifies": "If harmonic-zero's rejection rate climbs with curl the way "
                     "BT's does, it does not dominate BT and the null buys nothing.",
        "verdict": verdict,
        "value": {"alpha": ALPHA, "reps": reps, "k": k,
                  "n_cells_with_curl": len(with_curl), "n_cells_judged": len(usable),
                  "n_cells_excluded_for_separation": len(with_curl) - len(usable),
                  "harmonic_zero_max_reject": hz_max,
                  "bradley_terry_min_reject": bt_min, "rows": rows},
    }


# ---------------------------------------------------------------- probe 3
def harmonic_projected_eps(reps=1500, k=128):
    """Type-I inflation against ||P_h eps||, with a same-norm curl control.

    eps is INNOCENT misspecification, not a real cycle: rejections it causes are
    false. The claim is that the distortion is governed by the harmonic
    projection of eps alone, so an equal-norm perturbation inside S should move
    the rejection rate hardly at all.
    """
    rows = []
    for g in range(N_GRAPHS):
        edges = graph(g)
        D0, D1 = st.operators(N_ITEMS, edges, "observed")
        bases = st.harmonic_zero_bases(D0, D1)
        df = bases[0].shape[1]
        base = eta_in_S(D0, D1, 1.0, g)
        h_unit = flows.harmonic_unit(D0, D1)
        # eta_in_S guards this case; so must the control, which is built the same
        # way. Without 2-cells im D1^T = {0}, the norm below is 0, and every
        # control rate would come back NaN -- silently, since NaN comparisons are
        # False and json.dumps emits a bare NaN token.
        if not D1.shape[0]:
            raise ValueError(
                f"graph {g} has no 2-cells under filling='observed', so im D1^T "
                "= {0} and there is no in-S direction to build the control from. "
                "The control arm is the whole point of this probe.")
        c = seed("ctrl", g).normal(size=D1.shape[0])
        s_unit = D1.T @ c
        s_norm = float(np.linalg.norm(s_unit))
        if s_norm == 0.0:
            raise ValueError(
                f"graph {g}: the control draw landed in ker(D1^T), so it carries "
                "no in-S direction. Vary the seed rather than normalising by zero.")
        s_unit = s_unit / s_norm                          # unit, inside S
        for eps in (0.0, 0.05, 0.1, 0.2, 0.4, 0.8):
            row = {"graph": g, "eps": eps, "df": df,
                   "Ph_eps_norm": float(eps)}            # h_unit is unit & harmonic
            # The tag omits `name` so the two arms share a draw stream: common
            # random numbers at every eps, and at eps = 0 the arms have identical
            # eta, so they must agree EXACTLY -- a free check on the injection path.
            for name, direction in (("harmonic", h_unit), ("in_S_control", s_unit)):
                T, _, dropped = run_cell(base + eps * direction, k, bases,
                                         f"c3|{g}|{eps}", reps)
                row[f"{name}_n_usable"] = int(len(T))
                row[f"{name}_drop_rate"] = float(dropped / reps)
                row[f"{name}_reject"] = (float((T > chi2.ppf(1 - ALPHA, df)).mean())
                                         if len(T) > 20 else None)
            rows.append(row)
    usable = [r for r in rows if r["in_S_control_drop_rate"] < 0.05
              and r["harmonic_drop_rate"] < 0.05
              and r["in_S_control_reject"] is not None
              and r["harmonic_reject"] is not None]
    ctrl = [r["in_S_control_reject"] for r in usable]
    harm = [r["harmonic_reject"] for r in usable]
    verdict = ("confirmed" if usable and max(ctrl) < 0.10 and max(harm) > 0.20
               else "refuted" if usable else "inconclusive")
    return {
        "probe": "harmonic_projected_eps",
        "question": "Is the size distortion under innocent eps governed by "
                    "||P_h eps|| alone rather than by total eps?",
        "falsifies": "If an equal-norm perturbation inside S inflates the "
                     "rejection rate as much as the harmonic one, the null's "
                     "size depends on total eps and the claim is wrong.",
        "verdict": verdict,
        "value": {"alpha": ALPHA, "reps": reps, "k": k,
                  "n_cells": len(rows), "n_cells_judged": len(usable),
                  "n_cells_excluded_for_separation": len(rows) - len(usable),
                  "max_control_reject": max(ctrl, default=None),
                  "max_harmonic_reject": max(harm, default=None), "rows": rows},
    }


def _f(x, w, p):
    return ("%*.*f" % (w, p, x)) if x is not None else " " * (w - 2) + "--"


def _pc(x):
    return f"{100 * x:.1f}%"


def write_results_md():
    """Regenerate RESULTS.md from results/*.json so it cannot drift from the data.

    EVERY measured number below is an expression over the loaded json, never a
    literal. The prose is the part that drifts silently -- a table with a stale
    number looks stale, a sentence with one does not -- so the sentences read
    their numbers from the same rows the tables do. Only structural claims and
    the k=128/k=64 thinning framing are fixed text; thresholds and comparisons
    are derived, so a re-run with different constants rewrites them.
    """
    c = json.loads((RES / "chi2_collapse.json").read_text())
    f = json.loads((RES / "curl_freedom.json").read_text())
    e = json.loads((RES / "harmonic_projected_eps.json").read_text())
    cv, fv, ev = c["value"], f["value"], e["value"]

