"""Render the b1=0 rate comparison and state which of the three outcomes held."""
import json
from pathlib import Path

OUT = Path(__file__).parent / "results" / "b1_rate.json"


def main():
    d = json.loads(OUT.read_text())
    print(f"b1=0 rate, filling='{d['filling']}', p={d['p']}, {d['n_seeds']} seeds per cell")
    print("marginal = (small masks + b1=0)/N   [Sec 10's convention and seed_drop_rate's]")
    print("conditional = b1=0 / (N - small masks)\n")
    for n, rec in d["by_n"].items():
        print(f"=== n = {n} " + "=" * 58)
        a = rec["path_a_sec10"]
        print(f"  {'path':<28} {'marginal':>18} {'conditional':>18} {'small':>8}")
        print("  " + "-" * 74)
        print(f"  {'(a) Sec 10 recipe':<28} "
              f"{100*a['marginal_rate']:8.2f}% +/-{100*a['marginal_se']:.2f} "
              f"{100*a['conditional_rate']:8.2f}% +/-{100*a['conditional_se']:.2f} "
              f"{100*a['small_rate']:7.2f}%")
        for label, b in rec["path_b_floor"].items():
            print(f"  {'(b) floor ' + label:<28} "
                  f"{100*b['marginal_rate']:8.2f}% +/-{100*b['marginal_se']:.2f} "
                  f"{100*b['conditional_rate']:8.2f}% +/-{100*b['conditional_se']:.2f} "
                  f"{100*b['small_rate']:7.2f}%")
        for key in ("marginal", "conditional"):
            x = rec[f"{key}_across_cells"]
            z = rec[f"{key}_a_vs_b_pooled_z"]
            print(f"\n  {key}: across (gamma,eps) spread {x['spread_pp']:.2f} pp, "
                  f"chi2({x['dof']})={x['chi2']:.2f} -> "
                  f"{'homogeneous' if x['homogeneous'] else 'HETEROGENEOUS'}")
            print(f"  {key}: (a) vs each (b), pooled z = "
                  f"{', '.join(f'{v:+.2f}' for v in z)}  "
                  f"(|z|>2.5 would be a real gap)")
        print()


def write_md():
    d = json.loads(OUT.read_text())
    L = ["# The b1=0 rate: one statistic, measured twice", "",
         "Regenerated by `python report_b1.py`; do not edit by hand.", "",
         "Two numbers were in circulation for `n=6` under `filling='observed'`, `p=0.45`:",
         "the spec and paper's **64.7%** (Sec 10, Observation 2) and a **67.2%** measured",
         "during the build. Three things could have been true. This settles which.", "",
         "## Verdict: they were the same statistic", "",
         "The gap was sampling noise at the build's 64-seed budget. Nothing to fix in",
         "either code path, and Sec 10's estimate stands.", "",
         f"| n | pooled rate (25,000 masks) |", "|---|---|"]
    for n, p in d["pooled"].items():
        L.append(f"| {n} | **{100*p['rate']:.2f}% +/- {100*p['se']:.2f}** |")
    L += ["", "## The measurement", "",
          f"{d['n_seeds']} masks per cell, five independent seed streams per n:",
          "path (a) is the Sec 10 recipe `default_rng(77000 + s)`; path (b) is the floor",
          "path's own `derive_seed(\"floor_mask\", gamma, eps, s)` at four (gamma, eps).", "",
          "`marginal` counts small masks and `b1=0` together over all N -- Sec 10's",
          "convention, and the one `seed_drop_rate` uses. `conditional` is `b1=0` among",
          "fittable masks only. At n=6 roughly 1% of draws have fewer than 3 edges, so the",
          "two differ slightly; at n=12 they are identical.", ""]
    for n, rec in d["by_n"].items():
        L += [f"### n = {n}", "",
              "| path | marginal | conditional | small |", "|---|---|---|---|"]
        a = rec["path_a_sec10"]
        L.append(f"| (a) Sec 10 | {100*a['marginal_rate']:.2f}% +/-{100*a['marginal_se']:.2f} "
                 f"| {100*a['conditional_rate']:.2f}% +/-{100*a['conditional_se']:.2f} "
                 f"| {100*a['small_rate']:.2f}% |")
        for label, b in rec["path_b_floor"].items():
            L.append(f"| (b) floor {label} | {100*b['marginal_rate']:.2f}% +/-{100*b['marginal_se']:.2f} "
                     f"| {100*b['conditional_rate']:.2f}% +/-{100*b['conditional_se']:.2f} "
                     f"| {100*b['small_rate']:.2f}% |")
        x = rec["marginal_across_cells"]; z = rec["marginal_a_vs_b_pooled_z"]
        L += ["", f"Across the four (gamma, eps) cells: spread {x['spread_pp']:.2f} pp, "
                  f"chi-square({x['dof']}) = {x['chi2']:.2f} -- homogeneous.",
              f"Path (a) against each (b): pooled z = "
              f"{', '.join(f'{v:+.2f}' for v in z)}. No gap.", ""]
    sn = d["seed_noise_check"]
    L += ["## Why 67.2% and 64.7% differed", "",
          f"At n=6 the rate is near {100*sn['pooled_rate']:.0f}%, so a 64-seed estimate carries",
          f"a binomial standard error of **{100*sn['se_at_64_seeds']:.1f} pp**. 67.2% sits",
          f"{sn['z_for_0.672']:+.2f} sigma from the pooled value; "
          f"{100*sn['p_at_or_above_0.672']:.0f}% of 64-seed draws land at or above it.",
          f"The 95% range of a 64-seed estimate is "
          f"{100*sn['empirical_95_range_at_64_seeds'][0]:.0f}% to "
          f"{100*sn['empirical_95_range_at_64_seeds'][1]:.0f}%.", "",
          "A 64-seed budget cannot distinguish 64.7% from 67.2%, and was never going to.", "",
          "## What this rules out", "",
          "**The floor path's mask generation is independent of the latent.** The rate does",
          "not move with gamma or eps (chi-square 0.35 at n=6, 0.82 at n=12, both on 3 dof).",
          "It could have: `derive_seed` takes gamma and eps into the hash, so a dependence",
          "would have shown up here. It does not -- (gamma, eps) reindexes which draws you",
          "get, not which ensemble they come from.", "",
          "**The two code paths generate the same ensemble.** Every path-(a)-vs-(b)",
          "comparison is within 1.5 sigma at both n.", "",
          "## Note on Sec 10's own number", "",
          "Sec 10 used the first 3000 draws of path (a); this run reproduces that exactly",
          "(0.647000 at n=6, 0.113667 at n=12, bit-identical). Extending the same stream to",
          "5000 gives 65.60%. Those are nested samples, not independent ones, so the honest",
          "summary is the pooled 64.76% +/- 0.30 over all five streams.", "",
          "## Reproducing", "", "```bash", "python b1_rate.py     # ~2 min",
          "python report_b1.py   # renders this file", "```"]
    (OUT.parent.parent / "B1-RATE.md").write_text("\n".join(L) + "\n")


if __name__ == "__main__":
    main()
    write_md()
