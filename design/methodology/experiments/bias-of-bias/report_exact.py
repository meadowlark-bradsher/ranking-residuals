"""Render the exact-vs-MC run in the paper's Table 3 format."""
import json
from pathlib import Path

import numpy as np

OUT = Path(__file__).parent / "results" / "exact_energy_residual.json"


def main():
    d = json.loads(OUT.read_text())
    ex, mc = d["exact"], d["mc"]
    print(f"20-base-seed residual, exact energies vs Monte Carlo, matched topologies")
    print(f"(n_int=12, n_cplx=0, eps in {{0.1,0.2,0.4}}, gamma in {{1.0,1.5,2.0,3.0}}, "
          f"rho=1.5, k_min=c1/(rho*eps^2), shipped OLS)")
    print(f"{d['n_base_seeds']} base seeds x {ex['cells_per_seed']} cells "
          f"({ex['cells_per_seed'] - 4} with eps>0) x 64 inner seeds\n")
    w = 34
    print(f"  {'':<{w}}{'exact':>22}{'Monte Carlo':>22}")
    print("  " + "-" * (w + 44))

    def row(label, a, b, fmt="{:+.3f}%"):
        print(f"  {label:<{w}}{fmt.format(a):>22}{fmt.format(b):>22}")

    row("residual (mean)", ex["residual_pct"], mc["residual_pct"])
    row("s.e. over base seeds", ex["se_pct"], mc["se_pct"], "{:.3f} pt")
    row("per-draw min", ex["per_draw_min_pct"], mc["per_draw_min_pct"])
    row("per-draw max", ex["per_draw_max_pct"], mc["per_draw_max_pct"])
    row("per-draw spread", ex["per_draw_max_pct"] - ex["per_draw_min_pct"],
        mc["per_draw_max_pct"] - mc["per_draw_min_pct"], "{:.3f} pt")
    print()
    for e in ("0.1", "0.2", "0.4"):
        row(f"  residual at eps={e}", ex[f"residual_pct_eps_{e}"], mc[f"residual_pct_eps_{e}"])
    print()
    row("coverage (median of 16)", ex["coverage_median"], mc["coverage_median"], "{:.0f}")
    row("coverage (min-max)", ex["coverage_min"], mc["coverage_min"], "{:.0f}")
    p = d["paired_exact_minus_mc"]
    print(f"\n  paired exact - MC (ratio): {p['mean_pct']:+.3f} pt +/- {p['se_pct']:.3f}")
    print(f"  -> exact residual is {ex['residual_pct'] - mc['residual_pct']:+.3f} pt "
          f"relative to MC")


def write_md():
    """Emit EXACT-ENERGY.md from the recorded run, so the write-up cannot drift."""
    d = json.loads(OUT.read_text())
    ex, mc, p = d["exact"], d["mc"], d["paired_exact_minus_mc"]
    L = ["# Exact-energy residual, 20 base seeds", "",
         "Regenerated by `python report_exact.py`; do not edit by hand.", "",
         "The shipped residual is measured with Monte Carlo energies, so it mixes the",
         "OLS model's misspecification bias with sampling noise in the points being",
         "fitted. `exact_energy.py` replaces the MC average with the exact expectation",
         "", "```", "    E||P_h Y||^2 = mu' P_h mu + sum_i (P_h)_ii Var(Y_i)", "```", "",
         "summing the binomial pmf against the instrument's own clamped log-odds.",
         "Everything else is held identical: same masks, same theta, same latent, same",
         "derived window, same OLS. `verify_replica()` asserts the replica reproduces",
         "`rig.sweep.floor_measurement` bit-for-bit in MC mode, so the difference below",
         "is attributable to the energies alone.", "",
         "## Table 3 format", "",
         f"n_int=12, n_cplx=0, eps in {{0.1, 0.2, 0.4}}, gamma in {{1.0, 1.5, 2.0, 3.0}},",
         f"rho=1.5, window k_min = c1/(rho*eps^2), shipped OLS.",
         f"{d['n_base_seeds']} base seeds x {ex['cells_per_seed']} cells x 64 inner seeds.", "",
         "| | exact | Monte Carlo |", "|---|---|---|",
         f"| residual (mean) | **{ex['residual_pct']:+.3f}%** | **{mc['residual_pct']:+.3f}%** |",
         f"| s.e. over base seeds | {ex['se_pct']:.3f} pt | {mc['se_pct']:.3f} pt |",
         f"| per-draw min | {ex['per_draw_min_pct']:+.3f}% | {mc['per_draw_min_pct']:+.3f}% |",
         f"| per-draw max | {ex['per_draw_max_pct']:+.3f}% | {mc['per_draw_max_pct']:+.3f}% |",
         f"| per-draw spread | {ex['per_draw_max_pct']-ex['per_draw_min_pct']:.3f} pt | "
         f"{mc['per_draw_max_pct']-mc['per_draw_min_pct']:.3f} pt |",
         f"| residual at eps=0.1 | {ex['residual_pct_eps_0.1']:+.3f}% | {mc['residual_pct_eps_0.1']:+.3f}% |",
         f"| residual at eps=0.2 | {ex['residual_pct_eps_0.2']:+.3f}% | {mc['residual_pct_eps_0.2']:+.3f}% |",
         f"| residual at eps=0.4 | {ex['residual_pct_eps_0.4']:+.3f}% | {mc['residual_pct_eps_0.4']:+.3f}% |",
         f"| coverage (median of 16) | {ex['coverage_median']} | {mc['coverage_median']} |", "",
         f"Paired across identical topologies, exact - MC = {p['mean_pct']:+.3f} +/- "
         f"{p['se_pct']:.3f} pt: the two agree on the mean.", "",
         "## What changes", "",
         f"**The residual is real.** It survives removing every source of Monte Carlo",
         f"noise: {ex['residual_pct']:+.3f}% with a standard error of {ex['se_pct']:.3f} pt",
         "across base seeds. It is a property of the two-parameter fit, not of the sampling.", "",
         f"**The band around it was almost entirely noise.** The per-draw spread falls from",
         f"{mc['per_draw_max_pct']-mc['per_draw_min_pct']:.2f} pt to "
         f"{ex['per_draw_max_pct']-ex['per_draw_min_pct']:.3f} pt, a factor of "
         f"{(mc['per_draw_max_pct']-mc['per_draw_min_pct'])/(ex['per_draw_max_pct']-ex['per_draw_min_pct']):.0f}.",
         "The shipped claim that a single run \"lands anywhere in a band about a percentage",
         "point wide\" describes the Monte Carlo, not the estimator.", "",
         f"**It grows with eps**: {ex['residual_pct_eps_0.1']:+.3f}% -> "
         f"{ex['residual_pct_eps_0.2']:+.3f}% -> {ex['residual_pct_eps_0.4']:+.3f}% across the",
         "eps grid, with no MC noise anywhere in it. That independently confirms the",
         "`eps_dependence` probe and rules out the eps-independent variance-curvature channel.", "",
         "## The coverage result needs care", ""]
    L += ["Coverage falls from 15/16 to 0/16. That is not the estimator getting worse --",
          "the floor is unchanged. It is the interval getting narrower once MC noise is",
          "removed, while the bias stays put:", "",
          "| eps | CI width (exact) | CI width (MC) | ratio | bias |", "|---|---|---|---|---|"]
    for r in d["ci_evidence"]["rows"]:
        L.append(f"| {r['eps']} | {r['exact']['ci_width']:.2e} | {r['mc']['ci_width']:.2e} | "
                 f"{r['ci_width_ratio_mc_over_exact']:.0f}x | {r['exact']['bias']:+.2e} |")
    L += ["", "So the shipped 15/16 coverage is a statement about how wide sampling noise",
          "makes the interval, not evidence that the fit is unbiased. Read the two",
          "together: the bias is small (0.36%) and it is systematic, and the CI covers",
          "the oracle only because it is roughly two orders of magnitude wider than the",
          "bias it is being asked to detect.", "",
          "This does not overturn the paper's conclusion -- 0.36% is still small, and the",
          "rig still separates the floor from zero. It does mean coverage should not be",
          "cited as evidence of unbiasedness.", "",
          "## Reproducing", "", "```bash",
          "python exact_energy.py      # ~2 min, checkpointed per base seed",
          "python report_exact.py      # renders this file", "```", "",
          "The run is deterministic: masks and draws are seeded from the config",
          "fingerprint plus base seed, and the exact energies contain no RNG at all.",
          "Re-running reproduces these values rather than resampling them."]
    (OUT.parent.parent / "EXACT-ENERGY.md").write_text("\n".join(L) + "\n")


if __name__ == "__main__":
    main()
    write_md()
    print("\n  EXACT-ENERGY.md regenerated")
